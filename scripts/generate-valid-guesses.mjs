import fs from 'node:fs';
import wordListPath from 'word-list';

const sourceWords = fs.readFileSync(wordListPath, 'utf8').split('\n');

function wordsOfLength(length) {
  const pattern = new RegExp(`^[a-z]{${length}}$`);
  return [...new Set(sourceWords.filter((word) => pattern.test(word)))];
}

const words3 = wordsOfLength(3);
const words4 = wordsOfLength(4);
const output = `// Generated by npm run generate:words from word-list 4.1.0.\n`
  + `// Do not edit this file directly.\n`
  + `export const VALID_GUESSES_3 = new Set(${JSON.stringify(words3)});\n\n`
  + `export const VALID_GUESSES_4 = new Set(${JSON.stringify(words4)});\n`;

fs.writeFileSync(new URL('../src/validGuesses.js', import.meta.url), output);
console.log(`Generated ${words3.length} three-letter and ${words4.length} four-letter guesses.`);
